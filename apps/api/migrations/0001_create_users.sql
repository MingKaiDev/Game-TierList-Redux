-- Users who have signed in at least once. Created by GET /api/v1/me (R0 PR 6).
CREATE TABLE users (
  id           TEXT    PRIMARY KEY,          -- ULID, generated by the API
  firebase_uid TEXT    NOT NULL UNIQUE,      -- Firebase Auth uid (token "sub")
  display_name TEXT    NOT NULL,
  avatar_url   TEXT,
  created_at   INTEGER NOT NULL              -- unix epoch milliseconds
) STRICT;
